#ifndef GD32_HAL_PORT_H
#define GD32_HAL_PORT_H

#include "stm32_hal_cmsis_bridge.h"

/*
 * 以下地址取自 GD32F403 官方设备头文件。这里有意固化为目标 Port 常量：
 * public HAL 会把 GPIOA、USART1、SPI1、DMA1 等同名符号改成 STM32
 * 语义令牌，内部 Port 不能受头文件包含顺序影响。
 */
#define GD32_HAL_GPIOA_ADDRESS ((uint32_t)(GPIO_BASE + 0x00000000U))
#define GD32_HAL_GPIOB_ADDRESS ((uint32_t)(GPIO_BASE + 0x00000400U))
#define GD32_HAL_GPIOC_ADDRESS ((uint32_t)(GPIO_BASE + 0x00000800U))
#define GD32_HAL_GPIOD_ADDRESS ((uint32_t)(GPIO_BASE + 0x00000C00U))

#define GD32_HAL_USART0_ADDRESS 0x40013800UL
#define GD32_HAL_USART1_ADDRESS 0x40004400UL
#define GD32_HAL_USART2_ADDRESS 0x40004800UL
#define GD32_HAL_UART3_ADDRESS  0x40004C00UL
#define GD32_HAL_UART4_ADDRESS  0x40005000UL

#define GD32_HAL_TIMER0_ADDRESS  0x40012C00UL
#define GD32_HAL_TIMER1_ADDRESS  0x40000000UL
#define GD32_HAL_TIMER2_ADDRESS  0x40000400UL
#define GD32_HAL_TIMER3_ADDRESS  0x40000800UL
#define GD32_HAL_TIMER4_ADDRESS  0x40000C00UL
#define GD32_HAL_TIMER5_ADDRESS  0x40001000UL
#define GD32_HAL_TIMER6_ADDRESS  0x40001400UL
#define GD32_HAL_TIMER7_ADDRESS  0x40013400UL
#define GD32_HAL_TIMER8_ADDRESS  0x40014C00UL
#define GD32_HAL_TIMER9_ADDRESS  0x40015000UL
#define GD32_HAL_TIMER10_ADDRESS 0x40015400UL
#define GD32_HAL_TIMER11_ADDRESS 0x40001800UL
#define GD32_HAL_TIMER12_ADDRESS 0x40001C00UL
#define GD32_HAL_TIMER13_ADDRESS 0x40002000UL

#define GD32_HAL_ADC0_ADDRESS 0x40012400UL
#define GD32_HAL_I2C0_ADDRESS 0x40005400UL
#define GD32_HAL_I2C1_ADDRESS 0x40005800UL
#define GD32_HAL_SPI0_ADDRESS 0x40013000UL
#define GD32_HAL_SPI1_ADDRESS 0x40003800UL
#define GD32_HAL_SPI2_ADDRESS 0x40003C00UL

#define GD32_HAL_DMA0_ADDRESS 0x40020000UL
#define GD32_HAL_DMA1_ADDRESS 0x40020400UL
#define GD32_HAL_DMA_CHANNEL_ADDRESS(DMA_ADDRESS, CHANNEL) \
    ((uint32_t)((DMA_ADDRESS) + 0x08UL + (0x14UL * (uint32_t)(CHANNEL))))
#define GD32_HAL_DMA0_CHANNEL0_ADDRESS GD32_HAL_DMA_CHANNEL_ADDRESS(GD32_HAL_DMA0_ADDRESS, 0U)
#define GD32_HAL_DMA0_CHANNEL1_ADDRESS GD32_HAL_DMA_CHANNEL_ADDRESS(GD32_HAL_DMA0_ADDRESS, 1U)
#define GD32_HAL_DMA0_CHANNEL2_ADDRESS GD32_HAL_DMA_CHANNEL_ADDRESS(GD32_HAL_DMA0_ADDRESS, 2U)
#define GD32_HAL_DMA0_CHANNEL3_ADDRESS GD32_HAL_DMA_CHANNEL_ADDRESS(GD32_HAL_DMA0_ADDRESS, 3U)
#define GD32_HAL_DMA0_CHANNEL4_ADDRESS GD32_HAL_DMA_CHANNEL_ADDRESS(GD32_HAL_DMA0_ADDRESS, 4U)
#define GD32_HAL_DMA0_CHANNEL5_ADDRESS GD32_HAL_DMA_CHANNEL_ADDRESS(GD32_HAL_DMA0_ADDRESS, 5U)
#define GD32_HAL_DMA0_CHANNEL6_ADDRESS GD32_HAL_DMA_CHANNEL_ADDRESS(GD32_HAL_DMA0_ADDRESS, 6U)
#define GD32_HAL_DMA1_CHANNEL0_ADDRESS GD32_HAL_DMA_CHANNEL_ADDRESS(GD32_HAL_DMA1_ADDRESS, 0U)
#define GD32_HAL_DMA1_CHANNEL1_ADDRESS GD32_HAL_DMA_CHANNEL_ADDRESS(GD32_HAL_DMA1_ADDRESS, 1U)
#define GD32_HAL_DMA1_CHANNEL2_ADDRESS GD32_HAL_DMA_CHANNEL_ADDRESS(GD32_HAL_DMA1_ADDRESS, 2U)
#define GD32_HAL_DMA1_CHANNEL3_ADDRESS GD32_HAL_DMA_CHANNEL_ADDRESS(GD32_HAL_DMA1_ADDRESS, 3U)
#define GD32_HAL_DMA1_CHANNEL4_ADDRESS GD32_HAL_DMA_CHANNEL_ADDRESS(GD32_HAL_DMA1_ADDRESS, 4U)

#include "stm32_hal_port_api.h"

#endif /* GD32_HAL_PORT_H */
