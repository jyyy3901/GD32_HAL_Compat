/* ADC power/calibration 生命周期属于资源状态，不属于 HAL Handle 状态。 */
static uint8_t gd32HalAdc0CalibrationValid;

int GD32_HAL_ADC_IsCalibrationValid(uint32_t adc_address)
{
    return (adc_address == GD32_HAL_ADC0_ADDRESS) &&
           (gd32HalAdc0CalibrationValid != 0U);
}

void GD32_HAL_ADC_SetCalibrationValid(uint32_t adc_address)
{
    if (adc_address == GD32_HAL_ADC0_ADDRESS)
    {
        gd32HalAdc0CalibrationValid = 1U;
    }
}

void GD32_HAL_ADC_InvalidateCalibration(uint32_t adc_address)
{
    if (adc_address == GD32_HAL_ADC0_ADDRESS)
    {
        gd32HalAdc0CalibrationValid = 0U;
    }
}

static GD32_HAL_ResourceKind GD32_HAL_KindOf(const GD32_HAL_Resource *resource)
{
    const uint32_t token_kind = ((uint32_t)resource->semantic_id >> 8U) & 0xFFU;

    switch (token_kind)
    {
        case 0x01U: return GD32_HAL_RESOURCE_GPIO;
        case 0x02U: return GD32_HAL_RESOURCE_UART;
        case 0x03U: return GD32_HAL_RESOURCE_TIMER;
        case 0x04U: return GD32_HAL_RESOURCE_ADC;
        case 0x05U: return GD32_HAL_RESOURCE_DMA;
        case 0x06U: return GD32_HAL_RESOURCE_I2C;
        default: return GD32_HAL_RESOURCE_SPI;
    }
}

const GD32_HAL_Resource *GD32_HAL_ResolveInstance(uintptr_t stm32_instance,
                                                  GD32_HAL_ResourceKind kind)
{
    size_t index;

    for (index = 0U; index < (sizeof(gd32HalResources) / sizeof(gd32HalResources[0]));
         ++index)
    {
        if ((gd32HalResources[index].stm32_instance == stm32_instance) &&
            (GD32_HAL_KindOf(&gd32HalResources[index]) == kind))
        {
            return &gd32HalResources[index];
        }
    }
    return NULL;
}

const GD32_HAL_Resource *GD32_HAL_ResolveDMAChannelAddress(
    uint32_t channel_address)
{
    size_t index;

    for (index = 0U;
         index < (sizeof(gd32HalResources) / sizeof(gd32HalResources[0]));
         ++index)
    {
        if ((GD32_HAL_KindOf(&gd32HalResources[index]) ==
             GD32_HAL_RESOURCE_DMA) &&
            (gd32HalResources[index].gd32_instance == channel_address))
        {
            return &gd32HalResources[index];
        }
    }
    return NULL;
}

