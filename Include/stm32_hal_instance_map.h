#ifndef STM32_HAL_INSTANCE_MAP_H
#define STM32_HAL_INSTANCE_MAP_H

#include <stdint.h>

/*
 * 这些值是不可解引用的 STM32 语义令牌，不是 STM32 或 GD32 寄存器地址。
 * Port 层通过 GD32_HAL_ResolveInstance() 将令牌解析为目标资源。
 */
#define STM32_HAL_INSTANCE_TOKEN(KIND, INDEX) \
    (0xF4010000UL | ((uint32_t)(KIND) << 8U) | (uint32_t)(INDEX))

#define STM32_GPIO_INSTANCE_A STM32_HAL_INSTANCE_TOKEN(0x01U, 0x01U)
#define STM32_GPIO_INSTANCE_B STM32_HAL_INSTANCE_TOKEN(0x01U, 0x02U)
#define STM32_GPIO_INSTANCE_C STM32_HAL_INSTANCE_TOKEN(0x01U, 0x03U)
#define STM32_GPIO_INSTANCE_D STM32_HAL_INSTANCE_TOKEN(0x01U, 0x04U)

#define STM32_UART_INSTANCE_1 STM32_HAL_INSTANCE_TOKEN(0x02U, 0x01U)
#define STM32_UART_INSTANCE_2 STM32_HAL_INSTANCE_TOKEN(0x02U, 0x02U)
#define STM32_UART_INSTANCE_6 STM32_HAL_INSTANCE_TOKEN(0x02U, 0x06U)

#define STM32_TIM_INSTANCE_1  STM32_HAL_INSTANCE_TOKEN(0x03U, 0x01U)
#define STM32_TIM_INSTANCE_2  STM32_HAL_INSTANCE_TOKEN(0x03U, 0x02U)
#define STM32_TIM_INSTANCE_3  STM32_HAL_INSTANCE_TOKEN(0x03U, 0x03U)
#define STM32_TIM_INSTANCE_4  STM32_HAL_INSTANCE_TOKEN(0x03U, 0x04U)
#define STM32_TIM_INSTANCE_5  STM32_HAL_INSTANCE_TOKEN(0x03U, 0x05U)
#define STM32_TIM_INSTANCE_9  STM32_HAL_INSTANCE_TOKEN(0x03U, 0x09U)
#define STM32_TIM_INSTANCE_10 STM32_HAL_INSTANCE_TOKEN(0x03U, 0x0AU)
#define STM32_TIM_INSTANCE_11 STM32_HAL_INSTANCE_TOKEN(0x03U, 0x0BU)

#define STM32_ADC_INSTANCE_1 STM32_HAL_INSTANCE_TOKEN(0x04U, 0x01U)

#define STM32_DMA_INSTANCE(CONTROLLER, CHANNEL) \
    STM32_HAL_INSTANCE_TOKEN(0x05U, (((uint32_t)(CONTROLLER) << 4U) | \
                                     ((uint32_t)(CHANNEL) + 1U)))
#define STM32_DMA0_CHANNEL0 STM32_DMA_INSTANCE(0U, 0U)
#define STM32_DMA0_CHANNEL1 STM32_DMA_INSTANCE(0U, 1U)
#define STM32_DMA0_CHANNEL2 STM32_DMA_INSTANCE(0U, 2U)
#define STM32_DMA0_CHANNEL3 STM32_DMA_INSTANCE(0U, 3U)
#define STM32_DMA0_CHANNEL4 STM32_DMA_INSTANCE(0U, 4U)
#define STM32_DMA0_CHANNEL5 STM32_DMA_INSTANCE(0U, 5U)
#define STM32_DMA0_CHANNEL6 STM32_DMA_INSTANCE(0U, 6U)
#define STM32_DMA1_CHANNEL0 STM32_DMA_INSTANCE(1U, 0U)
#define STM32_DMA1_CHANNEL1 STM32_DMA_INSTANCE(1U, 1U)
#define STM32_DMA1_CHANNEL2 STM32_DMA_INSTANCE(1U, 2U)
#define STM32_DMA1_CHANNEL3 STM32_DMA_INSTANCE(1U, 3U)
#define STM32_DMA1_CHANNEL4 STM32_DMA_INSTANCE(1U, 4U)

#define STM32_I2C_INSTANCE_1 STM32_HAL_INSTANCE_TOKEN(0x06U, 0x01U)
#define STM32_I2C_INSTANCE_2 STM32_HAL_INSTANCE_TOKEN(0x06U, 0x02U)

#define STM32_SPI_INSTANCE_1 STM32_HAL_INSTANCE_TOKEN(0x07U, 0x01U)
#define STM32_SPI_INSTANCE_2 STM32_HAL_INSTANCE_TOKEN(0x07U, 0x02U)
#define STM32_SPI_INSTANCE_3 STM32_HAL_INSTANCE_TOKEN(0x07U, 0x03U)

/* GD32F403RET6 目标 IRQ ABI。集中定义，避免散落在各 HAL 模块头文件。 */
#define STM32_HAL_IRQ_ADC1            18
#define STM32_HAL_IRQ_TIM1_BRK_TIM9   24
#define STM32_HAL_IRQ_TIM1_UP_TIM10   25
#define STM32_HAL_IRQ_TIM1_TRG_TIM11  26
#define STM32_HAL_IRQ_TIM1_CC         27
#define STM32_HAL_IRQ_TIM2            28
#define STM32_HAL_IRQ_TIM3            29
#define STM32_HAL_IRQ_TIM4            30
#define STM32_HAL_IRQ_I2C1_EV         31
#define STM32_HAL_IRQ_I2C1_ER         32
#define STM32_HAL_IRQ_I2C2_EV         33
#define STM32_HAL_IRQ_I2C2_ER         34
#define STM32_HAL_IRQ_SPI1            35
#define STM32_HAL_IRQ_SPI2            36
#define STM32_HAL_IRQ_USART1          37
#define STM32_HAL_IRQ_USART2          38
#define STM32_HAL_IRQ_USART6          39
#define STM32_HAL_IRQ_TIM5            50
#define STM32_HAL_IRQ_SPI3            51

#endif /* STM32_HAL_INSTANCE_MAP_H */
